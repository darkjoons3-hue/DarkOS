[BITS 16]
[ORG 0x7C00]

start:
    ; Инициализация сегментов
    cli
    xor ax, ax
    mov ds, ax
    mov es, ax
    mov ss, ax
    mov sp, 0x7C00
    sti

    ; Указываем на видеопамять (текстовый режим 80x25, адрес 0xB8000)
    mov ax, 0xB800
    mov es, ax
    xor di, di          ; DI = 0 — начало видеопамяти

    ; Выводим строку "DarkOS booting..." посимвольно
    mov si, msg_hello
    mov ah, 0x0A        ; Атрибут: светло-зелёный текст на чёрном фоне

.print_loop:
    lodsb               ; Загружаем символ из [DS:SI] в AL
    test al, al         ; Проверяем, не конец ли строки
    jz .hang            ; Если 0 — выходим из цикла
    mov [es:di], ax     ; Записываем символ + атрибут в видеопамять
    add di, 2           ; Сдвигаем указатель на следующую ячейку (2 байта)
    jmp .print_loop

.hang:
    jmp $               ; Бесконечный цикл (процессор стоит на месте)

; Данные
msg_hello db 'DarkOS booting...', 0

; --- МАГИЯ ЗАГРУЗОЧНОГО СЕКТОРА ---
; Заполняем нулями до 510 байт
times 510 - ($ - $$) db 0
; Сигнатура загрузочного сектора (обязательна для BIOS)
dw 0xAA55

; --- РАСКАЧИВАЕМ ОБРАЗ ДО РАЗМЕРА ДИСКЕТЫ 1.44 МБ ---
; Чтобы Vectras VM понял, что это дискета, файл должен быть ровно 1 474 560 байт.
times 1474560 - ($ - $$) db 0
